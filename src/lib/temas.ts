/** Nome do tema com hífens opcionais (U+00AD), que só aparecem quando a palavra precisa quebrar. */
export function nomeQuebravel(tema: Tema): string {
  return tema.nome.replace(/\p{L}+/gu, (p) => SILABAS[p]?.replaceAll('-', '\u00AD') ?? p)
}

export function corDoTema(tema: Tema): string {
  return corDaArea(tema.area)
}

/** Cor do texto escrito sobre o círculo do tema: escuro nas cores claras, branco nas escuras. */
export function tintaDoTema(tema: Tema): string {
  const hex = corDoTema(tema).slice(1)
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16))
  return 0.299 * r + 0.587 * g + 0.114 * b > 150 ? 'var(--titulo)' : 'var(--branco)'
}
