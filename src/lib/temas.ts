function outros(area: string): Tema {
  const chave = normalizar(area).split(' ')[0]
  OUTROS[chave] ??= { id: `outros-${chave}`, nome: `Outros · ${area}`, area, chaves: [] }
  return OUTROS[chave]
}

const cache = new Map<string, Tema>()

/** Classifica um assunto em um tema geral. `area` é a disciplina onde o assunto apareceu. */
export function temaDoAssunto(texto: string, area: string): Tema {
  const id = normalizar(texto)
  const salvo = cache.get(id)
  if (salvo) return salvo
  const palavras = ' ' + id
  let tema: Tema | undefined
  let maior = 0
  for (const t of TEMAS) {
    for (const c of t.chaves) {
      if (c.length > maior && palavras.includes(' ' + c)) {
        tema = t
        maior = c.length
      }
    }
  }
  tema ??= outros(area)
  cache.set(id, tema)
  return tema
}

